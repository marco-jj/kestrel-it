import 'reflect-metadata';
import { LabelLayoutSchema } from '@kestrel-it/shared';
import {
  BarcodeFormat,
  BinaryBitmap,
  DecodeHintType,
  HybridBinarizer,
  MultiFormatReader,
  RGBLuminanceSource,
} from '@zxing/library';
import { PNG } from 'pngjs';
import { Readable } from 'node:stream';
import { describe, expect, it } from 'vitest';
import { automaticMapping, csvRows } from '../modules/inventory/import-mapping.js';
import {
  barcodeImage,
  labelGeometry,
  labelPresets,
  renderLabels,
} from '../modules/inventory/labels.controller.js';
import { notificationEvents } from '../modules/inventory/inventory-mail.service.js';
import { csvCell } from '../modules/inventory/reports.controller.js';
import {
  webhookPayload,
  webhookUrl,
  publicAddress,
} from '../modules/inventory/webhook-delivery.js';

describe('Snipe-IT operational format parity', () => {
  it.each([
    ['C128', BarcodeFormat.CODE_128, 'ASSET-01234', 'ASSET-01234', true],
    ['C39', BarcodeFormat.CODE_39, 'ASSET-01234', 'ASSET-01234', true],
    ['EAN13', BarcodeFormat.EAN_13, '590123412345', '5901234123457', true],
    ['UPCA', BarcodeFormat.UPC_A, '12345678901', '123456789012', true],
    ['ITF', BarcodeFormat.ITF, '12345678', '12345678', true],
    [
      'QRCODE',
      BarcodeFormat.QR_CODE,
      'https://kestrel.example.com/hardware/124',
      'https://kestrel.example.com/hardware/124',
      false,
    ],
    ['DATAMATRIX', BarcodeFormat.DATA_MATRIX, 'ASSET-0123456', 'ASSET-0123456', false],
    ['PDF417', BarcodeFormat.PDF_417, 'ASSET-0123456', 'ASSET-0123456', false],
  ] as const)(
    'decodes the %s symbol generated by the label renderer',
    async (format, decoder, input, output, linear) => {
      const image = PNG.sync.read(await barcodeImage(format, input, linear));
      const pixels = new Uint8ClampedArray(image.width * image.height);
      for (let i = 0; i < pixels.length; i++) {
        const offset = i * 4;
        pixels[i] = image.data[offset + 3] === 0 ? 255 : image.data[offset]!;
      }
      const reader = new MultiFormatReader();
      const bitmap = new BinaryBitmap(
        new HybridBinarizer(new RGBLuminanceSource(pixels, image.width, image.height)),
      );
      const hints = new Map([[DecodeHintType.POSSIBLE_FORMATS, [decoder]]]);
      expect(reader.decode(bitmap, hints).getText()).toBe(output);
    },
  );

  it('paginates Avery sheets and uses the requested roll dimensions', async () => {
    expect(labelGeometry(labelPresets.Avery5160!)).toEqual({ scale: 72, columns: 3, slots: 30 });
    expect(labelGeometry(labelPresets.Dymo30252!)).toEqual({ scale: 72, columns: 1, slots: 1 });
    const preset = {
      ...labelPresets.Avery5160!,
      skipped: 29,
      barcode: 'none' as const,
      code2d: 'none' as const,
    };
    const pdf = await renderLabels(
      preset,
      [
        { id: 1, asset_tag: 'A' },
        { id: 2, asset_tag: 'B' },
      ],
      'https://kestrel.example.com',
    );
    expect(pdf.toString('latin1')).toMatch(/\/Count 2\b/);
    expect(pdf.toString('latin1')).toMatch(/\/MediaBox \[0 0 612 792\]/);
    expect(() => labelGeometry(LabelLayoutSchema.parse({ ...preset, page_height: 0.5 }))).toThrow();
  });

  it('parses spreadsheet CSV input progressively with quoted delimiters and BOM', async () => {
    const csv = Readable.from([
      Buffer.from('\ufeffAsset Tag;Asset Name;Notes\r\nA-001;"Notebook; 1";"Line one\nLine two"'),
    ]);
    const result: string[][] = [];
    for await (const row of csvRows(csv)) result.push(row);
    expect(result).toEqual([
      ['Asset Tag', 'Asset Name', 'Notes'],
      ['A-001', 'Notebook; 1', 'Line one\nLine two'],
    ]);
    expect(automaticMapping('asset', result[0]!)).toEqual({
      0: 'asset_tag',
      1: 'name',
      2: 'notes',
    });
    expect(csvCell('\t=2+2')).toBe('"\'\t=2+2"');
    expect(csvCell('Line 1\n"Line 2"')).toBe('"Line 1\n""Line 2"""');
    const invalid = csvRows(Readable.from([Buffer.from('Name,Notes\nThing,"unfinished')]));
    await expect(
      (async () => {
        for await (const _ of invalid) {
          /* Consume the CSV. */
        }
      })(),
    ).rejects.toThrow();
  });

  it('uses a distinct event for each notification and encodes all supported webhook providers', () => {
    expect(new Set(notificationEvents).size).toBe(26);
    expect(webhookPayload('general', 'checkout.asset', 'Checkout', 'One')).toEqual({
      event: 'checkout.asset',
      title: 'Checkout',
      message: 'One',
    });
    expect(
      webhookPayload('slack', 'checkout.asset', 'Checkout', '<attachment>', 'inventory', 'Kestrel'),
    ).toEqual({
      text: 'Checkout\n&lt;attachment&gt;',
      channel: 'inventory',
      username: 'Kestrel',
    });
    expect(webhookPayload('google', 'checkout.asset', 'Checkout', 'One')).toEqual({
      text: 'Checkout\nOne',
    });
    expect(webhookPayload('microsoft', 'checkout.asset', 'Checkout', 'One')).toMatchObject({
      type: 'message',
      attachments: [
        {
          contentType: 'application/vnd.microsoft.card.adaptive',
          content: { type: 'AdaptiveCard' },
        },
      ],
    });
    expect(publicAddress('::ffff:127.0.0.1')).toBe(false);
    expect(publicAddress('169.254.169.254')).toBe(false);
    expect(() => webhookUrl('https://[::1]/hook')).toThrow();
    expect(() => webhookUrl('https://service.local/hook')).toThrow();
    expect(() => webhookUrl('https://user:secret@example.com/hook')).toThrow();
    expect(webhookUrl('https://hooks.example.com/hook').hostname).toBe('hooks.example.com');
  });
});
